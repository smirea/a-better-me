#!/usr/bin/env bun
import { readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import type { ExerciseSpec } from "../src/exercise";
import { MOTION_ROOT } from "./catalog-io";

const exercisesDir = join(MOTION_ROOT, "src", "exercises");
const files = readdirSync(exercisesDir)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts" && !f.startsWith("_"))
  .sort();

const seenIds = new Set<string>();
const seenCatalogIds = new Set<string>();
const imports: string[] = [];
const names: string[] = [];

for (let i = 0; i < files.length; i++) {
  const file = files[i];
  const stem = file.slice(0, -3);
  const full = resolve(join(exercisesDir, file));
  const mod = (await import(full)) as Record<string, unknown>;
  let exportName = "spec";
  let specObj: ExerciseSpec | undefined;
  if (mod.spec && typeof mod.spec === "object" && "build" in mod.spec) {
    specObj = mod.spec as ExerciseSpec;
  } else {
    for (const [k, v] of Object.entries(mod)) {
      if (v && typeof v === "object" && "id" in v && "catalogId" in v && "build" in v) {
        exportName = k;
        specObj = v as ExerciseSpec;
        break;
      }
    }
  }
  if (!specObj) {
    throw new Error(`${file}: does not export an ExerciseSpec.`);
  }
  if (specObj.id !== stem) {
    throw new Error(`${file}: spec.id "${specObj.id}" must match filename "${stem}".`);
  }
  if (seenIds.has(specObj.id)) {
    throw new Error(`Duplicate exercise id "${specObj.id}" in ${file}.`);
  }
  if (seenCatalogIds.has(specObj.catalogId)) {
    throw new Error(`Duplicate catalogId "${specObj.catalogId}" in ${file}.`);
  }
  seenIds.add(specObj.id);
  seenCatalogIds.add(specObj.catalogId);
  const alias = `ex${i}`;
  imports.push(`import { ${exportName} as ${alias} } from "./${stem}";`);
  names.push(alias);
}

const out = `// Auto-generated by scripts/sync-exercises.ts — do not edit by hand.
import type { ExerciseSpec } from "../exercise";
${imports.join("\n")}

export const EXERCISES: ExerciseSpec[] = [
${names.map((n) => `  ${n},`).join("\n")}
];
`;

writeFileSync(join(exercisesDir, "index.ts"), out);
console.log(`Synced ${files.length} exercises into exercise-motion/src/exercises/index.ts`);
