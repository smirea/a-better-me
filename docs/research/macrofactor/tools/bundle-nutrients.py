"""Regenerate the nutrient table in nutrients.md from the MacroFactor bundle.

Joins four native sources on the nutrient id: the App Intents `NutrientAppEnum`
(order, title, synonyms, SF Symbol), the widget intent definition (`m`-prefixed
codes), the widget's unit-bearing labels, and StrongerModels' four name forms.
Rewrites only the lines between the generated markers in nutrients.md, then
formats the file with the repo's oxfmt, as the pre-commit hook would.

Usage: python3 -I tools/bundle-nutrients.py [MacroFactor.app]
"""
import json
import re
import subprocess
import sys
from pathlib import Path

MF = Path(sys.argv[1] if len(sys.argv) > 1 else "/Applications/MacroFactor.app")
RUNNER = MF / "Wrapper/Runner.app"
WIDGET = RUNNER / "PlugIns/mfwidgetsExtension.appex"
DOC = Path(__file__).resolve().parent.parent / "nutrients.md"
START, END = "<!-- generated:nutrients:start -->", "<!-- generated:nutrients:end -->"

for required in (RUNNER, DOC):
    if not required.exists():
        sys.exit(f"missing {required}")


def plist(path):
    out = subprocess.run(["plutil", "-convert", "json", "-o", "-", str(path)], capture_output=True, check=True)
    return json.loads(out.stdout)


actions = json.loads((RUNNER / "Metadata.appintents/extract.actionsdata").read_text())
enum = next(e for e in actions["enums"] if e["identifier"] == "NutrientAppEnum")
intents = plist(WIDGET / "Base.lproj/Intents.intentdefinition")
codes = {
    v["INEnumValueDisplayName"]: v["INEnumValueName"]
    for e in intents["INEnums"]
    if e["INEnumName"] == "Nutrients"
    for v in e["INEnumValues"]
    if v["INEnumValueName"] != "unknown"
}
labels = plist(WIDGET / "en.lproj/Localizable.strings").values()
units = {}
for label in labels:
    m = re.fullmatch(r"(.+) \((g|mg|mcg|mL)\)", label)
    if m:
        units[m.group(1)] = m.group(2)
forms = plist(RUNNER / "StrongerModels_StrongerModels.bundle/en.lproj/Localizable.strings")

# Each source names a few nutrients its own way; the first candidate name that the source knows wins.
LABEL_EXTRA = {"901": "Omega-3", "902": "Omega-6"}
FORM_EXTRA = {"nc": "Net Carbs (Non-fiber)", "851": "Omega 3 ALA", "629": "Omega 3 EPA", "621": "Omega 3 DHA"}
widget_names = {code: name for name, code in codes.items()}


def first(candidates, known):
    return next((c for c in candidates if c and c in known), None)


rows = []
for case in enum["cases"]:
    nid = case["identifier"]
    rep = case["displayRepresentation"]
    title = rep["title"]["key"]
    code = f"m{nid}"
    if code not in widget_names:
        sys.exit(f"no widget code for {nid}")
    widget_name = widget_names[code]
    label = first([widget_name, title, LABEL_EXTRA.get(nid)], units)
    unit = units[label] if label else "kcal" if nid == "k" else "g"
    key = first([FORM_EXTRA.get(nid), widget_name, title], {k.rsplit("_", 1)[0] for k in forms})
    if not key:
        sys.exit(f"no StrongerModels names for {nid}")
    names = [forms[f"{key}_{form}"] for form in ("COMPLETE", "SENTENCE", "SHORT", "MINI")]
    rows.append([
        nid,
        code,
        title,
        widget_name,
        ", ".join(s["key"] for s in rep["synonyms"]),
        unit,
        *names,
        rep["image"]["systemImageName"]["_0"],
    ])

header = ["Id", "Widget code", "Intent title", "Widget name", "Synonyms", "Unit", "Complete", "Sentence", "Short", "Mini", "SF Symbol"]
table = [
    f"Generated by `python3 -I tools/bundle-nutrients.py` from MacroFactor "
    f"{plist(RUNNER / 'Info.plist')['CFBundleShortVersionString']}. {len(rows)} nutrients, in `NutrientAppEnum` order.",
    "",
    "| " + " | ".join(header) + " |",
    "|" + "---|" * len(header),
    *("| " + " | ".join(f"`{c}`" if i in (0, 1, 10) else c for i, c in enumerate(row)) + " |" for row in rows),
]
doc = DOC.read_text()
if START not in doc or END not in doc:
    sys.exit(f"{DOC} lacks the generated markers")
before, rest = doc.split(START, 1)
_, after = rest.split(END, 1)
DOC.write_text(before + START + "\n" + "\n".join(table) + "\n" + END + after)
subprocess.run(["bunx", "oxfmt", str(DOC)], cwd=DOC.parents[3], check=True, capture_output=True)
