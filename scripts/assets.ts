/**
 * The large catalog files the app downloads after install instead of bundling, kept in the private R2 bucket
 * `a-better-me-assets` as content-addressed `blobs/<sha256>` plus one `manifests/<version>.json` per asset version.
 *
 *   bun scripts/assets.ts version   hash app-ios/Assets and rewrite app-ios/Config/Assets.xcconfig (no network)
 *   bun scripts/assets.ts upload    upload the missing blobs, then the manifest (needs this Mac's AWS access)
 *
 * Never prints a credential: it logs counts and sizes only.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ASSETS_DIR, computeManifest, type Manifest } from '../server/src/assets';
import { readEnv } from './lib';

const XCCONFIG_PATH = new URL('../app-ios/Config/Assets.xcconfig', import.meta.url).pathname;
const BUCKET = 'a-better-me-assets';
const UPLOAD_CONCURRENCY = 16;

const sha256 = (data: string | Uint8Array) => createHash('sha256').update(data).digest('hex');
const megabytes = (bytes: number) => `${(bytes / 1e6).toFixed(1)} MB`;

/** The version the app bundles, from the tracked `Assets.xcconfig`, or null when it has none. */
export function trackedVersion(): string | null {
	return /^ASSETS_VERSION\s*=\s*([0-9a-f]+)\s*$/m.exec(readFileSync(XCCONFIG_PATH, 'utf8'))?.[1] ?? null;
}

export function writeVersion(): Manifest {
	const manifest = computeManifest(ASSETS_DIR);
	writeFileSync(
		XCCONFIG_PATH,
		`// Generated by bun run assets version from app-ios/Assets. Do not edit.\nASSETS_VERSION = ${manifest.version}\n`,
	);
	const bytes = manifest.files.reduce((sum, file) => sum + file.size, 0);
	console.log(`Asset version ${manifest.version}: ${manifest.files.length} files, ${megabytes(bytes)}`);
	return manifest;
}

/** R2 takes any Cloudflare API token as S3 credentials: the token's id and the sha256 of its value. */
async function bucket(): Promise<Bun.S3Client> {
	const values = readEnv('prod');
	const account = values.CLOUDFLARE_ACCOUNT_ID;
	const token = values.CLOUDFLARE_API_TOKEN;
	if (!account || !token) throw new Error('Not set in env-manager prod: CLOUDFLARE_ACCOUNT_ID, CLOUDFLARE_API_TOKEN');
	const response = await fetch('https://api.cloudflare.com/client/v4/user/tokens/verify', {
		headers: { authorization: `Bearer ${token}` },
	});
	const body = (await response.json()) as { success: boolean; result?: { id: string } };
	if (!body.success || !body.result) throw new Error(`Cloudflare rejected CLOUDFLARE_API_TOKEN (${response.status})`);
	return new Bun.S3Client({
		accessKeyId: body.result.id,
		secretAccessKey: sha256(token),
		endpoint: `https://${account}.r2.cloudflarestorage.com`,
		bucket: BUCKET,
		region: 'auto',
	});
}

async function existingBlobs(client: Bun.S3Client): Promise<Set<string>> {
	const keys = new Set<string>();
	let continuationToken: string | undefined;
	do {
		const page = await client.list({ prefix: 'blobs/', continuationToken });
		for (const object of page.contents ?? []) keys.add(object.key);
		continuationToken = page.isTruncated ? page.nextContinuationToken : undefined;
	} while (continuationToken);
	return keys;
}

/** Idempotent. The manifest goes last, so a manifest in the bucket never names a missing blob. */
export async function upload() {
	const manifest = computeManifest(ASSETS_DIR);
	if (trackedVersion() !== manifest.version) {
		throw new Error(`app-ios/Config/Assets.xcconfig is stale for app-ios/Assets. Run bun run assets version.`);
	}
	const client = await bucket();
	const existing = await existingBlobs(client);
	const missing = [
		...new Map(
			manifest.files.filter(file => !existing.has(`blobs/${file.sha256}`)).map(file => [file.sha256, file]),
		).values(),
	];
	const bytes = missing.reduce((sum, file) => sum + file.size, 0);
	console.log(`${missing.length} of ${manifest.files.length} blobs to upload (${megabytes(bytes)})`);
	let next = 0;
	const worker = async () => {
		while (next < missing.length) {
			const file = missing[next++]!;
			await client.write(`blobs/${file.sha256}`, readFileSync(join(ASSETS_DIR, file.path)), {
				type: 'application/octet-stream',
			});
		}
	};
	await Promise.all(Array.from({ length: UPLOAD_CONCURRENCY }, worker));
	await client.write(`manifests/${manifest.version}.json`, JSON.stringify(manifest), { type: 'application/json' });
	console.log(`Uploaded manifests/${manifest.version}.json`);
}

if (import.meta.main) {
	const commands: Record<string, () => unknown> = { version: writeVersion, upload };
	const command = commands[process.argv[2] ?? ''];
	if (!command) {
		console.error(`Usage: bun scripts/assets.ts <${Object.keys(commands).join('|')}>`);
		process.exit(1);
	}
	await command();
}
