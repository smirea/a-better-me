const BREAKFAST = ['', 'breakfast'];
const f = (
	name: string | string[],
	amount: number,
	unit: string | string[],
	meal?: string | string[],
	extra: Expected = {},
): Expected => ({
	kind: 'food',
	name: typeof name === 'string' ? [name] : name,
	amount,
	unit,
	...(meal === undefined ? {} : { meal }),
	...extra,
});
const copy = (id: string, meal: string, except: string[] = [], extra: Expected = {}): Expected => ({
	kind: 'copy',
	copy: id,
	meal,
	except,
	...extra,
});
