/**
 * Writes `server/drizzle` as the module `server/src/db/migrations.generated.ts`, since the Worker cannot read the
 * migration files: `bun scripts/bundle-migrations.ts`. `bun run db:generate` runs it after drizzle-kit, and CI fails
 * when the committed module is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dir, '..');
const journal = JSON.parse(readFileSync(join(root, 'server/drizzle/meta/_journal.json'), 'utf8')) as {
	entries: { tag: string; when: number }[];
};
const migrations = journal.entries.map(entry => ({
	tag: entry.tag,
	when: entry.when,
	statements: readFileSync(join(root, `server/drizzle/${entry.tag}.sql`), 'utf8')
		.split('--> statement-breakpoint')
		.map(statement => statement.trim())
		.filter(Boolean),
}));
writeFileSync(
	join(root, 'server/src/db/migrations.generated.ts'),
	`// Generated by scripts/bundle-migrations.ts from server/drizzle. Do not edit.\nexport const migrations: { tag: string; when: number; statements: string[] }[] = ${JSON.stringify(migrations, null, '\t')};\n`,
);
